#!/usr/bin/env node

/**
 * Database Backup Script
 * Creates a SQL dump of all tables in the database
 */

import mysql from 'mysql2/promise'
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import dotenv from 'dotenv'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

// Load environment variables
dotenv.config({ path: path.join(__dirname, '..', '.env') })

const config = {
  host: process.env.MYSQL_HOST || 'localhost',
  port: parseInt(process.env.MYSQL_PORT || '3306'),
  user: process.env.MYSQL_USER || 'root',
  password: process.env.MYSQL_PASSWORD || '',
  database: process.env.MYSQL_DATABASE || 'stpaulus_cms_db'
}

async function backupDatabase() {
  let connection
  
  try {
    console.log('🔄 Connecting to database...')
    connection = await mysql.createConnection(config)
    console.log('✅ Connected to database:', config.database)

    // Create backups directory
    const backupsDir = path.join(__dirname, '..', 'backups')
    if (!fs.existsSync(backupsDir)) {
      fs.mkdirSync(backupsDir, { recursive: true })
    }

    // Generate filename with timestamp
    const timestamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, -5)
    const filename = `stpaulus_backup_${timestamp}.sql`
    const filepath = path.join(backupsDir, filename)

    console.log('📦 Creating backup file:', filename)

    // Start SQL dump
    let sqlDump = `-- MySQL Database Backup
-- Database: ${config.database}
-- Date: ${new Date().toISOString()}
-- Generated by: StPaulus Backup Script
--
-- =====================================================

SET FOREIGN_KEY_CHECKS=0;
SET SQL_MODE="NO_AUTO_VALUE_ON_ZERO";
SET time_zone = "+00:00";

`

    // Get all tables
    const [tables] = await connection.query('SHOW TABLES')
    const tableNames = tables.map(row => Object.values(row)[0])

    console.log(`📊 Found ${tableNames.length} tables to backup`)

    // Backup each table
    for (const tableName of tableNames) {
      console.log(`   ⏳ Backing up table: ${tableName}`)

      // Get CREATE TABLE statement
      const [createResult] = await connection.query(`SHOW CREATE TABLE \`${tableName}\``)
      const createStatement = createResult[0]['Create Table']

      sqlDump += `\n-- =====================================================\n`
      sqlDump += `-- Table structure for: ${tableName}\n`
      sqlDump += `-- =====================================================\n\n`
      sqlDump += `DROP TABLE IF EXISTS \`${tableName}\`;\n`
      sqlDump += createStatement + ';\n\n'

      // Get table data
      const [rows] = await connection.query(`SELECT * FROM \`${tableName}\``)

      if (rows.length > 0) {
        sqlDump += `-- =====================================================\n`
        sqlDump += `-- Data for table: ${tableName}\n`
        sqlDump += `-- =====================================================\n\n`
        sqlDump += `INSERT INTO \`${tableName}\` VALUES\n`

        const values = rows.map((row, index) => {
          const escapedValues = Object.values(row).map(val => {
            if (val === null) return 'NULL'
            if (typeof val === 'number') return val
            if (val instanceof Date) return `'${val.toISOString().slice(0, 19).replace('T', ' ')}'`
            // Escape single quotes and backslashes
            const escaped = String(val).replace(/\\/g, '\\\\').replace(/'/g, "\\'")
            return `'${escaped}'`
          })
          const valueStr = `(${escapedValues.join(', ')})`
          return valueStr
        })

        sqlDump += values.join(',\n') + ';\n\n'
      }
    }

    sqlDump += `\nSET FOREIGN_KEY_CHECKS=1;\n`

    // Write to file
    fs.writeFileSync(filepath, sqlDump, 'utf8')

    // Get file size
    const stats = fs.statSync(filepath)
    const fileSizeInMB = (stats.size / (1024 * 1024)).toFixed(2)

    console.log('\n✅ Backup completed successfully!')
    console.log(`📁 File: ${filename}`)
    console.log(`💾 Size: ${fileSizeInMB} MB`)
    console.log(`📂 Location: ${filepath}`)

  } catch (error) {
    console.error('\n❌ Backup failed:', error.message)
    console.error('Error details:', error)
    process.exit(1)
  } finally {
    if (connection) {
      await connection.end()
    }
  }
}

// Run backup
backupDatabase()
